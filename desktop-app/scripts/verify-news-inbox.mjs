assert.equal(inbox.messages.length, 2);
assert(inbox.messages.every(message => !message.notified && !message.read));
inbox = updateNewsMessage(inbox, one.id, 'notify');
assert.equal(inbox.messages.find(message => message.id === one.id).notified, true);
assert.equal(inbox.messages.find(message => message.id === one.id).read, false, 'popup does not claim the full mail was read');
inbox = normalizeNewsInbox(JSON.parse(JSON.stringify(inbox)));
assert.equal(inbox.messages.filter(message => !message.notified).length, 1, 'restart does not replay a shown popup');
inbox = updateNewsMessage(inbox, two.id, 'read');
assert.equal(inbox.messages.find(message => message.id === two.id).read, true);
assert.equal(inbox.messages.length, 2, 'reading/closing is not deletion');
inbox = updateNewsMessage(inbox, one.id, 'delete');
assert.equal(inbox.messages.length, 1);
inbox = mergeNewsFeed(normalizeNewsInbox(JSON.parse(JSON.stringify(inbox))), normalizeNewsFeed(envelope([{ ...one, title: 'Edited ID' }, two]), now), now + NEWS_CHECK_MS);
assert.equal(inbox.messages.length, 1, 'deleted mail never reappears when feed is checked/edited');
inbox = mergeNewsFeed(inbox, [], now + 2 * NEWS_CHECK_MS);
assert.equal(inbox.messages.length, 1, 'withdrawn/expired feed entries do not silently delete saved mail');
inbox = updateNewsMessage(inbox, two.id, 'delete');
assert.equal(inbox.messages.length, 0);
assert.deepEqual(inbox.seenIds.sort(), [one.id, two.id]);
assert.equal(newsCheckDue(inbox, now + 2 * NEWS_CHECK_MS + 1), false);
assert.equal(newsCheckDue(inbox, now + 3 * NEWS_CHECK_MS), true);
assert.equal(newsCheckDue(inbox, now - 1), true, 'clock rollback does not freeze checks forever');
assert.equal(normalizeNewsInbox({ messages: [{ ...one, id: '../invalid' }], seenIds: ['good', '../bad'], lastCheckedAt: Infinity }).messages.length, 0);
