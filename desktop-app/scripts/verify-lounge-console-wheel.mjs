import assert from 'node:assert/strict';
import fs from 'node:fs';
import { advanceConsoleWheel } from '../src/components/lounge/lounge-console-wheel.mjs';
import { nextLoungeConsole, LOUNGE_CONSOLES } from '../src/components/lounge/lounge-emulator-zone.mjs';
const wheel = (deltaY, extra = {}) => ({ deltaY, deltaX: 0, deltaMode: 0, ...extra });
let result = advanceConsoleWheel({}, wheel(120), 0);
assert.equal(result.direction, 1, 'first mouse detent moves immediately');
assert.equal(result.handled, true);
assert.equal(advanceConsoleWheel(result.state, wheel(120), 20).direction, 0, 'rapid events are bounded');
assert.equal(advanceConsoleWheel(result.state, wheel(120), 100).direction, 1);
assert.equal(advanceConsoleWheel(result.state, wheel(-120), 100).direction, -1, 'reverse does not retain forward momentum');
let trackpad = advanceConsoleWheel({}, wheel(24), 0);
assert.equal(trackpad.direction, 0);
assert.equal(advanceConsoleWheel(trackpad.state, wheel(24), 20).direction, 1);
assert.equal(advanceConsoleWheel(trackpad.state, wheel(24), 300).direction, 0, 'stale gesture remainder expires');
assert.equal(advanceConsoleWheel({}, wheel(0, { deltaX: -120 }), 0).direction, -1);
assert.equal(advanceConsoleWheel({}, wheel(2, { deltaMode: 1 }), 0).direction, 1);
assert.equal(advanceConsoleWheel({}, wheel(1, { deltaMode: 2 }), 0).direction, 1);
assert.equal(advanceConsoleWheel({}, wheel(120, { ctrlKey: true }), 0).handled, false);
assert.equal(advanceConsoleWheel({}, wheel(NaN), 0).handled, false);
assert.equal(nextLoungeConsole(LOUNGE_CONSOLES.at(-1).id, 1), LOUNGE_CONSOLES[0].id);
const source = fs.readFileSync(new URL('../src/components/lounge/NeoLounge.jsx', import.meta.url), 'utf8');
assert(!source.includes('lounge-console-summary'), 'no duplicate status text beside the console strip');
for (const direction of ['left', 'right']) assert(source.includes(`hidden tabIndex={-1} aria-hidden="true" data-lounge-console-step="${direction}"`), 'controller step targets are hidden and excluded from focus');
assert(!source.includes('ChevronLeft') && !source.includes('ChevronRight'), 'console arrows are not rendered');
assert.match(source, /surface.addEventListener\('wheel', onWheel, \{ passive: false \}\)/);
assert.match(source, /\[layout, shownGames.length > 0, zone, consoleGamesOpen\]/, 'game wheel handler reconnects when console games mount');
assert.match(source, /if \(!inDock && \(consoleGamesOpen/, 'open games retain their own wheel lane');
assert.match(source, /chooseConsole\(next\)/, 'wheel only selects consoles, never activates them');
console.log('PASS: console wheel, trackpad accumulation, reverse, wrap, zoom preservation and game-row remount.');
