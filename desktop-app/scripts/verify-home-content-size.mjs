import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { normalizeHomeContentSize, homeContentSize, homeContentSizePatch } from '../src/components/home/home-content-size.mjs';
import { homeEditorSavePatch } from '../src/components/home/home-layout-editor-model.mjs';
import { DEFAULT_HOME_TITLE, normalizeHomeTitle, homeTitleTweaks, homeTitlePatch, homeTitleStyles } from '../src/components/home/home-title-tweaks.mjs';
import { hydrateSettings } from '../src/state/settings-state.mjs';

assert.deepEqual(normalizeHomeTitle(), DEFAULT_HOME_TITLE);
assert.deepEqual(normalizeHomeTitle({ size:Infinity, weight:'bad', color:'url(evil)', contrast:NaN, uppercase:'true' }), DEFAULT_HOME_TITLE);
assert.equal(normalizeHomeTitle({size:999,contrast:999}).size,26);
assert.equal(normalizeHomeTitle({size:0,contrast:999}).contrast,90);
let titles = { titleTweaks:{size:16,color:'bright'},widgetTitleTweaks:{news:{size:24}},freePositions:{news:{x:10,y:30,width:500,height:400}},communityWidgetConfig:{test:{grants:[]}} };
assert.equal(homeTitleTweaks(titles,'news').size,24);
assert.equal(homeTitleTweaks(titles,'recent').size,16);
assert.equal(homeTitleTweaks(titles,'news').color,'bright');
titles = {...titles,...homeTitlePatch(titles,'news','contrast',70)};
titles = {...titles,...homeTitlePatch(titles,'','weight',600)};
assert.equal(homeTitleTweaks(titles,'news').weight,600,'untouched per-widget fields continue following shared controls');
assert.equal(homeTitleTweaks(titles,'news').contrast,70);
assert.equal(hydrateSettings(JSON.parse(JSON.stringify({homeLayout:titles}))).homeLayout.widgetTitleTweaks.news.size,24);
assert.deepEqual(homeTitlePatch(titles,'news','unknown',10),{});
assert.equal(homeTitleStyles({size:26}).bar.minHeight,45);
assert.equal(homeTitleStyles({size:26}).iconSize,30);
const withTitlePatch={...titles,...homeTitlePatch(titles,'recent','size',20)};
assert.deepEqual(withTitlePatch.freePositions,titles.freePositions);
assert.deepEqual(withTitlePatch.communityWidgetConfig,titles.communityWidgetConfig);

for (const value of [undefined, null, NaN, Infinity, 'bad']) assert.equal(normalizeHomeContentSize(value), 100);
assert.equal(normalizeHomeContentSize(20), 100);
assert.equal(normalizeHomeContentSize(10000), 180);
assert.equal(normalizeHomeContentSize('128'), 130);
const layout = { contentSize: 140, widgetContentSizes: { news: 170 }, hidden: ['storage'], communityWidgetConfig: { demo: { grants: [] } }, freePositions: { news: { x: 20, y: 30, width: 450, height: 300 } } };
assert.equal(homeContentSize(layout, 'news'), 170);
assert.equal(homeContentSize(layout, 'recent'), 140);
assert.equal(homeContentSize({}, 'news'), 100);
assert.deepEqual(homeContentSizePatch(layout, '', 160), { contentSize: 160 });
assert.deepEqual(homeContentSizePatch(layout, 'recent', 150), { widgetContentSizes: { news: 170, recent: 150 } });
const next = { ...layout, ...homeContentSizePatch(layout, 'recent', 150) };
assert.deepEqual(next.freePositions, layout.freePositions, 'content sizing must not mutate outer boxes');
assert.deepEqual(next.hidden, layout.hidden);
assert.deepEqual(next.communityWidgetConfig, layout.communityWidgetConfig);
assert.equal(homeContentSize(JSON.parse(JSON.stringify(next)), 'recent'), 150, 'saved presentation survives JSON persistence');
const editorPatch = homeEditorSavePatch(next, { order: ['news'], positions: next.freePositions, snap: true }, ['news']);
assert.equal(homeContentSize({ ...next, ...editorPatch }, 'recent'), 150, 'arrangement save preserves content sizing');
const read = name => fs.readFileSync(new URL(`../src/components/${name}`, import.meta.url), 'utf8');
const home = read('HomeHub.jsx');
assert(home.includes('contentSize={homeContentSize(homeLayout, id)}'));
assert(home.includes('zoom: contentSize / 100, minWidth: 0'));
assert(home.includes('home-widget-content-scale'));
assert(home.includes('data-testid="home-widget-settings-button"'));
assert(!home.includes('transform: `scale(${contentSize'), 'no scaled/shrinking outer canvas');
const settings = read('home/HomeWidgetSettings.jsx');
const toolbar = home.slice(home.indexOf('<header'), home.indexOf('</header>'));
assert.equal((toolbar.match(/Edit widgets/g) || []).length, 1);
for (const oldLabel of ['Rearrange widgets', 'Import widget', 'Snap on', 'Widget settings', 'Customize Home']) assert(!toolbar.includes(oldLabel), `keep ${oldLabel} inside the widget panel`);
for (const action of ['onRearrange', 'onImport', 'onToggleSnap']) assert(home.includes(`${action}=`) && settings.includes(action));
for (const label of ['Rearrange widgets', 'Import widget', 'Snap on', 'Widget settings']) assert(settings.includes(label));
assert(!settings.includes('onManage') && !settings.includes('>Choose widgets'), 'visibility choices belong inside Rearrange, not a separate manager button');
assert(home.includes('setWidgetSettingsOpen(false); startWidgetImport();'), 'close the hub before the import guide opens');
assert(home.includes('setWidgetSettingsOpen(false); toggleLayoutLock();'), 'close the hub before the arrangement editor opens');
for (const text of ['Widget content size', 'Reset all content sizes', 'Use shared size', 'aria-modal="true"', 'data-controller-close', "event.key !== 'Tab'", 'previous.focus()']) assert(settings.includes(text));
const require = createRequire(import.meta.url);
const babel = createRequire(require.resolve('@vitejs/plugin-react'))('@babel/core');
babel.parseSync(settings, { configFile: false, babelrc: false, parserOpts: { plugins: ['jsx'] } });
console.log('PASS: Home shared/per-widget content sizing is bounded, persistent and independent of canvas geometry, arrangement and permissions; settings keyboard/controller wiring verified. Live visual acceptance pending.');
