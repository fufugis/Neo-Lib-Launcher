import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { reminderTimestamp, makeCalendarReminder, normalizeCalendarReminders, nextCalendarReminder } from '../src/components/home/calendar-reminder-model.mjs';
import { normalizeCalendarPreferences } from '../src/components/home/playtime-calendar-model.mjs';
const now = new Date(2026,9,20,8).getTime();
const item=makeCalendarReminder({day:'2026-10-21',time:'09:30',text:' Play with friends '},now,'first');
assert.equal(new Date(item.at).getHours(),9);
assert.equal(new Date(item.at).getDate(),21);
assert.equal(item.text,'Play with friends');
for(const [day,time] of [['2026-02-30','10:00'],['2026-10-21','24:00'],['bad','09:00'],['2026-10-21','09:65']])assert(Number.isNaN(reminderTimestamp(day,time)));
assert.throws(()=>makeCalendarReminder({day:'2026-10-19',time:'09:30',text:'Past'},now,'past'));
assert.throws(()=>makeCalendarReminder({day:'2026-10-21',time:'09:30',text:' '},now,'empty'));
assert.equal(normalizeCalendarReminders({version:1,items:[item,item]}).length,1);
assert.deepEqual(normalizeCalendarReminders(JSON.parse(JSON.stringify({version:1,items:[item]}))),[item]);
assert.throws(()=>normalizeCalendarReminders({version:2,items:[]}));
assert.equal(nextCalendarReminder([item],now),null);
assert.equal(nextCalendarReminder([item],item.at).id,'first');
assert.equal(nextCalendarReminder([{...item,announced:true}],item.at).id,'first','Unacknowledged reminder survives restart');
assert.equal(nextCalendarReminder([{...item,acknowledged:true}],item.at),null);
assert.equal(normalizeCalendarPreferences({year:9999},new Date(now),{allowFuture:true}).year,2031);
assert.equal(normalizeCalendarPreferences({year:9999},new Date(now)).year,2026,'Lounge heatmap retains historical limits');
assert.equal(makeCalendarReminder({day:'2026-10-21',time:'09:30',text:'a'.repeat(1200)},now,'bounded').text.length,1000);
assert.equal(nextCalendarReminder([{...item,id:'later',at:item.at+60000},item],item.at+60000).id,'first');
const dst=spawnSync(process.execPath,['--input-type=module','-e',`import assert from 'node:assert/strict';import{reminderTimestamp}from ${JSON.stringify(new URL('../src/components/home/calendar-reminder-model.mjs',import.meta.url).href)};assert(Number.isNaN(reminderTimestamp('2030-03-31','02:30')));assert(Number.isFinite(reminderTimestamp('2030-03-31','03:30')));`],{env:{...process.env,TZ:'Europe/Oslo'},encoding:'utf8'});
assert.equal(dst.status,0,dst.stderr);
console.log('PASS: local reminder date/time validation, future-only save, note bounds, normalized persistence, duplicates, due ordering/restart/acknowledgement and Home-only future navigation.');
