import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { emulatorIdentity, normalizeRetroProfiles, isRomGame, statisticsGames, resolveRomLaunch, recordedMinutesInPeriod, gameLaunchContext } from '../src/lib/emulator-profile-model.mjs';
import { romLibraryEntry } from '../src/lib/emulation-library-model.mjs';
import { sessionResult } from '../src/state/playtime-state.mjs';
import { playtimePie } from '../src/components/home/playtime-pie-model.mjs';
import { playtimeCalendar } from '../src/components/home/playtime-calendar-model.mjs';
import { projectLoungeGames } from '../src/components/modules/module-model.mjs';
assert.equal(emulatorIdentity('C:/Apps/PCSX2-qt.exe').platform, 'ps2');
assert.equal(emulatorIdentity('C:/Apps/PPSSPPWindows64.exe').platform, 'psp');
assert.equal(emulatorIdentity('C:/Apps/Dolphin.exe').platform, 'generic', 'multi-system identity must not guess the ROM console');
assert.equal(emulatorIdentity('C:/Apps/Dolphin.exe').argumentPrefix, '-b -e');
assert.equal(emulatorIdentity('C:/Apps/Cemu.exe').argumentPrefix, '-g');
assert.equal(emulatorIdentity('C:/Apps/Mystery.exe').name, 'Mystery');
const profile = { id: 'retro-one', name: 'My emulator', platform: 'snes', emulatorPath: 'C:/Emulators/old.exe', romFolder: 'D:/My ROMs', icon: 'data:image/png;base64,YQ==', argumentPrefix: '--fullscreen' };
const normalized = normalizeRetroProfiles([profile, { ...profile }]);
assert.equal(normalized.length, 1); assert.equal(normalized[0].icon, profile.icon);
assert.equal(normalizeRetroProfiles([{ ...profile, icon: 'https://tracker.test/image.png' }])[0].icon, '');
assert.equal(normalizeRetroProfiles([{ ...profile, icon: 'javascript:bad' }])[0].icon, '');
assert.equal(normalizeRetroProfiles(Array.from({ length: 30 }, (_, i) => ({ ...profile, id: `retro-${i}` }))).length, 30, 'legacy twenty-profile truncation is removed');
const rom = { ...romLibraryEntry({ profile, romPath: 'D:/My ROMs/Mario.sfc', now: 1 }), id: 'rom-one', playtime: 30, playtimeDays: { '2026-10-13': 30 } };
assert(isRomGame(rom));
const resolved = resolveRomLaunch(rom, [{ ...profile, emulatorPath: 'C:/Emulators/new.exe' }]);
assert.equal(resolved.game.id, rom.id); assert.equal(resolved.game.exePath, 'C:/Emulators/new.exe');
assert.equal(resolved.game.launchArgs, '--fullscreen "D:/My ROMs/Mario.sfc"');
assert(resolveRomLaunch(rom, []).error);
assert.equal(gameLaunchContext(rom, [{ ...profile, trackingMethod: 'manual' }], [], true).trackPlaytime, false);
assert.equal(gameLaunchContext(rom, [profile], [], true).toolLaunch, false, 'Lounge ROM is a game even when the main view shows Tools');
assert.equal(gameLaunchContext(rom, [profile], [], true).trackPlaytime, true);
assert(resolveRomLaunch(rom, [{ ...profile, platform: 'ps2' }]).error);
const mame = resolveRomLaunch({ ...rom, romPath: 'D:/Arcade/pacman.zip', retroPlatform: 'arcade' }, [{ ...profile, platform: 'arcade', emulatorId: 'mame', argumentPrefix: '' }]);
assert.equal(mame.game.launchArgs, '-rompath "D:/Arcade" "pacman"');
const app = { id: 'emulator-app', name: 'RetroArch', launcher: 'emulator', exePath: profile.emulatorPath, playtime: 500 };
const pc = { id: 'pc', name: 'PC game', playtime: 60, playtimeDays: { '2026-10-13': 60 } };
assert.deepEqual(statisticsGames([rom, app, pc]).map(game => game.id), ['rom-one', 'pc']);
assert.deepEqual(statisticsGames([rom, app, pc], true).map(game => game.id), ['pc']);
assert.equal(sessionResult(app, 600).patch, null);
assert.equal(sessionResult(rom, 600).patch.playtime, 40);
assert.equal(recordedMinutesInPeriod(rom, 7, new Date(2026, 9, 13, 12)), 30);
assert.equal(recordedMinutesInPeriod({ ...rom, playtimeDays: {} }, 7, new Date(2026, 9, 13, 12)), 0, 'do not invent dated ROM history from lifetime totals');
assert.equal(playtimePie([rom, app, pc]).total, 90);
assert.equal(playtimePie([rom, app, pc], { excludeRoms: true }).total, 60);
assert.equal(playtimeCalendar([rom, app, pc], { view: 'year', year: 2026 }, new Date(2026, 9, 13, 12)).total, 90);
assert.equal(playtimeCalendar([rom, app, pc], { view: 'year', year: 2026, excludeRoms: true }, new Date(2026, 9, 13, 12)).total, 60);
const projected = projectLoungeGames([rom]);
assert(isRomGame(projected[0])); assert(!('romPath' in projected[0]) && !('exePath' in projected[0]), 'detached Lounge can classify a ROM without private host paths');
assert.equal(playtimePie(projected, { excludeRoms: true }).total, 0);
const read = path => fs.readFileSync(new URL(path, import.meta.url), 'utf8');
const panel = read('../src/components/wizard/RetroProfilesPanel.jsx');
for (const text of ['+ Add emulator', 'Add ROM folder', 'extractIcon', 'scanSequence', 'metadataSource', 'Choose icon']) assert(panel.includes(text));
assert(!panel.includes('launchGame('), 'adding emulator/ROM folder never launches anything');
const appSource = read('../src/App.jsx');
assert(appSource.includes('gameLaunchContext(g, settings.retroProfiles'));
const loungeSource = read('../src/components/lounge/NeoLounge.jsx');
assert(loungeSource.includes('...(pendingPreferences.current || preferences), playtimePieFilters'));
assert(loungeSource.includes('...(pendingPreferences.current || preferences), playtimeCalendarPreferences'));
assert(appSource.includes('.filter(game => !isRomGame(game))'), 'external shared-process watcher cannot guess the active ROM');
assert(appSource.includes('useGameSessionEvents({ enabled: isElectron'));
const sessionEvents = read('../src/hooks/use-game-session-events.mjs');
assert(/if\s*\(!gameId\s*\|\|\s*trackingDisabled\)\s*return/.test(sessionEvents), 'native emulator opt-out survives session-hook extraction');
const require = createRequire(import.meta.url), babel = createRequire(require.resolve('@vitejs/plugin-react'))('@babel/core');
babel.parseSync(panel, { configFile: false, babelrc: false, parserOpts: { plugins: ['jsx'] } });
console.log('PASS: executable-first emulator rows, local identification/icons, profile persistence, multi-system caution, current-profile ROM routes, distinct ROM playtime, statistics exclusions and path-free Lounge classification. Actual emulator launch/controller acceptance remains separate.');
