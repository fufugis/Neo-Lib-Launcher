import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { gameArtworkCandidates, explicitArtwork } from '../src/lib/artwork-fallbacks.mjs';
import { requestSteamArtwork } from '../src/lib/steam-artwork-cache.mjs';
const { createSteamArtworkService, parseSteamArtwork } = createRequire(import.meta.url)('../electron/providers/steam-artwork-service.cjs');
const hash = 'a'.repeat(40);
const item = id => ({ appid: Number(id), success: 1, item_type: 0, assets: { community_icon: hash, asset_url_format: 'steam/apps/' + id + '/${FILENAME}?t=123', library_capsule: hash + '/library_600x900.jpg' } });
let calls = 0, offline = false;
const service = createSteamArtworkService({ httpGetJson: async url => {
  calls++; if (offline) throw Error('offline');
  const ids = JSON.parse(new URL(url).searchParams.get('input_json')).ids.map(v => v.appid);
  return { response: { store_items: ids.map(item) } };
} });
const rows = await service.getMany(['620','400','620']);
assert.equal(calls, 1); assert.equal(rows.length, 2);
assert.match(rows[0].icon, /\/public\/images\/apps\/620\/a{40}\.jpg$/);
assert.match(rows[0].portraitImage, /\/620\/a{40}\/library_600x900.jpg\?t=123$/);
await service.getMany(['400']); assert.equal(calls, 1, 'positive cache');
assert.deepEqual(await service.getMany(['../secret']), []);
assert.deepEqual(await service.getMany(Array(41).fill('620')), []);
const untrusted = item('620'); untrusted.assets.community_icon = '../secret'; untrusted.assets.library_capsule = '../private.jpg';
assert.deepEqual(parseSteamArtwork(untrusted,'620'), { appid:'620', icon:'', portraitImage:'', portraits:[] });
assert.equal(parseSteamArtwork(item('400'),'620'), null);
offline = true; assert.deepEqual(await service.getMany(['123']), []); offline = false;
assert.equal((await service.getMany(['123'])).length, 1, 'offline errors do not poison native cache');
const apiCalls = [];
let active = 0, peak = 0;
const api = { async steamArtwork(ids) { apiCalls.push(ids); peak = Math.max(peak, ++active); await new Promise(r=>setTimeout(r,10)); active--; return ids.map(id=>({appid:id,icon:'https://test/icon-'+id})); } };
const work = Array.from({length:93},(_,i)=>requestSteamArtwork(api,String(i+1)));
assert.equal(requestSteamArtwork(api,'1'),work[0], 'duplicate consumers share one promise');
await Promise.all(work);
assert(apiCalls.every(ids=>ids.length<=40)); assert.equal(apiCalls.length,3); assert(peak<=2);
await requestSteamArtwork(api,'1'); assert.equal(apiCalls.length,3);
assert.equal(await requestSteamArtwork({},'620'),null);
assert.equal(await requestSteamArtwork({steamArtwork:async()=>{throw Error('offline')}},'620'),null);
const banner = 'https://shared.akamai.steamstatic.com/store_item_assets/steam/apps/620/header.jpg';
const game = { appid:'620', icon:banner, coverUrl:banner, steamArtwork:rows[0] };
assert.equal(gameArtworkCandidates(game,'icon')[0],rows[0].icon);
assert.equal(gameArtworkCandidates(game,'cover')[0],rows[0].portraitImage);
assert(gameArtworkCandidates(game,'cover').includes(banner), 'last-resort banner remains usable');
for (const role of ['icon','cover']) {
  const chosen={...game,artworkSources:{[role]:'Player selected'}};
  assert(explicitArtwork(chosen,role));
  assert.equal(gameArtworkCandidates(chosen,role)[0],banner);
  assert.equal(gameArtworkCandidates({...game,artworkLocks:{[role]:true}},role)[0],banner);
  assert.equal(gameArtworkCandidates({...game,artworkSources:{[role]:'steamgriddb'}},role)[0],banner,'Reviewed provider selections also retain priority');
}
assert.equal(game.icon,banner,'render-time repair does not overwrite saved choices');
console.log('PASS: Steam square-icon/portrait discovery, identity/path safety, batched bounded lookup/cache/offline recovery and role priority/custom-choice preservation.');
