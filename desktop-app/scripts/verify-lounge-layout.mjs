import assert from 'node:assert/strict';
import fs from 'node:fs';
import { applyLoungePreset, applyLoungeVisualPreset, DEFAULT_LOUNGE_PREFERENCES, LOUNGE_PARTICLE_IDS, LOUNGE_PRESETS, LOUNGE_VISUAL_PRESETS, matchesLoungeVisualPreset, normalizeLoungePreferences } from '../src/components/lounge/lounge-layout-model.mjs';
import { hydrateSettings, mergeSettings } from '../src/state/settings-state.mjs';

const defaults = normalizeLoungePreferences(null);
assert.equal(defaults.shelfPosition, 'top');
assert.equal(defaults.previewStyle, 'cinema');
assert.equal(defaults.entryScreen, 'games', 'existing installs still enter the game browser by default');
assert.equal(defaults.controlSize, 'comfortable');
assert.equal(defaults.browseSort, 'library');
assert.equal(hydrateSettings({ loungePreferences: { browseSort: 'name' } }).loungePreferences.browseSort, 'name');
assert.equal(normalizeLoungePreferences({ browseSort: 'bogus' }).browseSort, 'library');
assert.equal(defaults.ambientPace, 'steady');
assert.equal(normalizeLoungePreferences({ ambientPace: 'slow' }).ambientPace, 'slow');
assert.equal(hydrateSettings({ loungePreferences: { ambientPace: 'lively' } }).loungePreferences.ambientPace, 'lively');
assert.equal(normalizeLoungePreferences({ ambientPace: 'chaotic' }).ambientPace, 'steady');
assert.equal(normalizeLoungePreferences({ controlSize: 'large' }).controlSize, 'large');
assert.equal(hydrateSettings({ loungePreferences: { controlSize: 'large' } }).loungePreferences.controlSize, 'large');
assert.equal(normalizeLoungePreferences({ controlSize: 'huge' }).controlSize, 'comfortable');
assert.equal(normalizeLoungePreferences({ entryScreen: 'home' }).entryScreen, 'home');
assert.equal(hydrateSettings({ loungePreferences: { entryScreen: 'home' } }).loungePreferences.entryScreen, 'home');
assert.equal(normalizeLoungePreferences({ entryScreen: 'bogus' }).entryScreen, 'games');
assert.equal(defaults.particleStyle, 'theme');
assert(LOUNGE_PARTICLE_IDS.includes('falling-heart'));
const particleCatalog = JSON.parse(fs.readFileSync(new URL('../electron/themes/builtin-particles.json', import.meta.url), 'utf8'));
assert.deepEqual(LOUNGE_PARTICLE_IDS.slice(2), particleCatalog.map(item => item.id));
assert.equal(normalizeLoungePreferences({ particleStyle: 'rain-drop' }).particleStyle, 'rain-drop');
assert.equal(normalizeLoungePreferences({ particleStyle: 'bad' }).particleStyle, 'theme');
assert.equal(hydrateSettings({ loungePreferences: { particleStyle: 'warm-ember' } }).loungePreferences.particleStyle, 'warm-ember');
assert.equal(defaults.browseSoundEnabled, true);
assert.equal(defaults.browseSoundVolume, 25);
assert.equal(defaults.browseMoveLevel, 100);
assert.equal(normalizeLoungePreferences({ browseMoveLevel: 0 }).browseMoveLevel, 0);
assert.equal(hydrateSettings({ loungePreferences: { browseMoveLevel: 40 } }).loungePreferences.browseMoveLevel, 40);
assert.equal(normalizeLoungePreferences({ browseMoveLevel: 1000 }).browseMoveLevel, 100);
assert.equal(defaults.browseSoundStyle, 'glass');
assert.equal(defaults.ambienceTrack, 'none', 'new and upgraded installs must not start music unexpectedly');
assert.equal(normalizeLoungePreferences({ ambienceTrack: 'ambience-4', ambienceVolume: 80 }).ambienceTrack, 'ambience-4');
assert.equal(hydrateSettings({ loungePreferences: { ambienceTrack: 'ambience-2', ambienceVolume: 40 } }).loungePreferences.ambienceVolume, 40);
assert.equal(normalizeLoungePreferences({ ambienceTrack: 'unknown', ambienceVolume: 200 }).ambienceTrack, 'none');
assert.equal(normalizeLoungePreferences({ ambienceVolume: 200 }).ambienceVolume, 100);
assert.equal(normalizeLoungePreferences({ ambienceCustomUrl: 'https://example.com/track.mp3' }).ambienceCustomUrl, '');
assert.equal(normalizeLoungePreferences({ ambienceTrack: 'custom', ambienceCustomUrl: 'https://example.com/track.mp3' }).ambienceTrack, 'none');
assert.equal(normalizeLoungePreferences({ ambienceCustomUrl: 'file:///C:/Users/Player/NEO-LIB/lounge-audio/my%20song.mp3' }).ambienceCustomUrl, 'file:///C:/Users/Player/NEO-LIB/lounge-audio/my%20song.mp3');
assert.equal(normalizeLoungePreferences({ browseSoundStyle: 'orbit' }).browseSoundStyle, 'orbit');
assert.equal(normalizeLoungePreferences({ browseSoundStyle: 'unknown' }).browseSoundStyle, 'glass');
assert.equal(normalizeLoungePreferences({ browseSoundEnabled: false, browseSoundVolume: 250 }).browseSoundVolume, 100);
assert.equal(normalizeLoungePreferences({ browseSoundVolume: -5 }).browseSoundVolume, 0);
assert.equal(hydrateSettings({ loungePreferences: { browseSoundEnabled: false, browseSoundVolume: 45 } }).loungePreferences.browseSoundEnabled, false);
assert.equal(hydrateSettings({ loungePreferences: { browseSoundStyle: 'pulse' } }).loungePreferences.browseSoundStyle, 'pulse');
for (const [id, preset] of Object.entries(LOUNGE_PRESETS)) {
  const selected = applyLoungePreset(defaults, id);
  assert.equal(selected.preset, id);
  assert.equal(selected.shelfPosition, preset.shelfPosition);
  assert.equal(normalizeLoungePreferences(selected).shelfPosition, preset.shelfPosition);
}
const custom = normalizeLoungePreferences({ ...defaults, preset: 'custom', shelfPosition: 'left', coverSize: 140, stageHeight: 620, motion: 'subtle', fxLevel: 3 });
assert.equal(hydrateSettings({ loungePreferences: custom }).loungePreferences.shelfPosition, 'left');
assert.equal(mergeSettings({}, { loungePreferences: custom }).loungePreferences.fxLevel, 3);
const visual = normalizeLoungePreferences({ backdropMode: 'image', backgroundUrl: 'file://C:/Art/my-lounge.webp', backgroundOpacity: 42, panelOpacity: 70, ambientMotion: 'waves', waveStrength: 58 });
assert.equal(hydrateSettings({ loungePreferences: visual }).loungePreferences.backgroundUrl, visual.backgroundUrl);
assert.equal(normalizeLoungePreferences({ backgroundUrl: 'file:///C:/Users/Player/NEO-LIB/lounger%20art.webp' }).backgroundUrl, 'file:///C:/Users/Player/NEO-LIB/lounger%20art.webp');
assert.equal(visual.backdropMode, 'image');
assert.equal(normalizeLoungePreferences({ backdropMode: 'game' }).backdropMode, 'game');
assert.equal(normalizeLoungePreferences({ backgroundPositionY: -20 }).backgroundPositionY, 0);
assert.equal(normalizeLoungePreferences({ backgroundPositionY: 140 }).backgroundPositionY, 100);
assert.equal(hydrateSettings({ loungePreferences: { backgroundPositionY: 72 } }).loungePreferences.backgroundPositionY, 72);
for (const id of Object.keys(LOUNGE_VISUAL_PRESETS)) {
  const preset = applyLoungeVisualPreset({ ...visual, shelfPosition: 'left' }, id);
  assert.equal(preset.shelfPosition, 'left', 'visual presets preserve Lounge layout');
  assert.equal(preset.backgroundUrl, visual.backgroundUrl, 'visual presets do not discard imported art');
  assert.equal(matchesLoungeVisualPreset(preset, id), true);
  assert.equal(hydrateSettings({ loungePreferences: preset }).loungePreferences.backdropMode, preset.backdropMode);
}
assert.equal(applyLoungeVisualPreset(visual, 'invalid').backgroundUrl, visual.backgroundUrl);
assert.equal(matchesLoungeVisualPreset(visual, 'invalid'), false);
assert.equal(matchesLoungeVisualPreset({ ...applyLoungeVisualPreset(visual, 'cinema'), panelOpacity: 99 }, 'cinema'), false);
assert.equal(visual.backgroundOpacity, 42);
assert.equal(visual.panelOpacity, 70);
assert.equal(visual.ambientMotion, 'waves');
assert.equal(visual.waveStrength, 58);
const home = normalizeLoungePreferences({ homeTileOrder: ['visual', 'all', 'visual', 'bogus'], homeHiddenTiles: ['favorites', 'favorites', 'bogus'] });
assert.deepEqual(home.homeTileOrder, ['visual', 'all', 'continue', 'favorites', 'recent', 'added', 'most']);
assert.deepEqual(home.homeHiddenTiles, ['favorites']);
assert.deepEqual(hydrateSettings({ loungePreferences: home }).loungePreferences.homeTileOrder, home.homeTileOrder);
assert.equal(normalizeLoungePreferences({ homeShowNextUp: false }).homeShowNextUp, false);
assert.equal(normalizeLoungePreferences({ homeShowRecentlyAdded: false }).homeShowRecentlyAdded, false);
assert.equal(hydrateSettings({ loungePreferences: { homeShowRecentlyAdded: false } }).loungePreferences.homeShowRecentlyAdded, false);
assert.equal(hydrateSettings({ loungePreferences: { homeShowNextUp: false } }).loungePreferences.homeShowNextUp, false);
const hostile = normalizeLoungePreferences({ shelfPosition: 'url(javascript:bad)', coverSize: 100000, gap: -20, stageHeight: 'huge', shelfWidth: Infinity, previewStyle: '<style>', infoDensity: 'bad', motion: 'bad', fxLevel: 900 });
assert.equal(hostile.shelfPosition, defaults.shelfPosition);
assert.equal(hostile.coverSize, 184);
assert.equal(hostile.gap, 8);
assert.equal(hostile.stageHeight, defaults.stageHeight);
assert.equal(hostile.shelfWidth, defaults.shelfWidth);
assert.equal(hostile.previewStyle, defaults.previewStyle);
assert.equal(hostile.fxLevel, 'theme');
assert.equal(normalizeLoungePreferences({ backdropMode: 'bad', backgroundUrl: 'https://example.com/script.png', backgroundOpacity: 999, panelOpacity: -1, ambientMotion: 'script', waveStrength: -5 }).backgroundUrl, '');
assert.equal(normalizeLoungePreferences({ backgroundOpacity: 999, panelOpacity: -1, waveStrength: -5 }).backgroundOpacity, 100);
assert.equal(normalizeLoungePreferences({ backgroundOpacity: 999, panelOpacity: -1, waveStrength: -5 }).panelOpacity, 40);
assert.deepEqual(normalizeLoungePreferences(DEFAULT_LOUNGE_PREFERENCES), defaults);
console.log('PASS: Lounge presets, bounded customization and saved-setting hydration.');
